const dictionaries: Record<Lang, Record<Key, string>> = { en, hi };

export const LANGUAGES: { key: Lang; label: string }[] = [
  { key: 'en', label: 'English' },
  { key: 'hi', label: 'हिंदी' }
];

/** Every key in the dictionary — used by tests to keep the two in step. */
export const KEYS = Object.keys(en) as Key[];

export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: Key, params?: Params): string {
  const template = (dictionaries[lang] ?? en)[key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole
  );
}
